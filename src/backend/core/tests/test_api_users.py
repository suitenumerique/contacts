"""
Test users API endpoints in the contacts core app.
"""

import pytest
from rest_framework.test import APIClient

from core import factories, models
from core.api import serializers

pytestmark = pytest.mark.django_db


@pytest.mark.parametrize("method", ["get", "post", "delete"])
def test_api_users_list_endpoint_does_not_exist(method):
    """There is no user listing or search: people suggestion is not this app's job."""
    user = factories.UserFactory()
    client = APIClient()
    client.force_login(user)

    response = getattr(client, method)("/api/v1.0/users/")

    assert response.status_code == 404


def test_api_users_retrieve_me_anonymous():
    """Anonymous users should not be allowed to retrieve "/users/me"."""
    factories.UserFactory.create_batch(2)
    client = APIClient()
    response = client.get("/api/v1.0/users/me/")
    assert response.status_code == 401
    assert response.json() == {
        "errors": [
            {
                "attr": None,
                "code": "not_authenticated",
                "detail": "Authentication credentials were not provided.",
            },
        ],
        "type": "client_error",
    }


def test_api_users_retrieve_me_authenticated():
    """Authenticated users should be able to retrieve their own user via the "/users/me" path."""
    user = factories.UserFactory()

    client = APIClient()
    client.force_login(user)

    factories.UserFactory.create_batch(2)
    response = client.get(
        "/api/v1.0/users/me/",
    )

    assert response.status_code == 200
    assert response.json() == {
        "id": str(user.id),
        "email": user.email,
        "full_name": user.full_name,
        "language": user.language,
        "can_access": True,
        "is_admin": False,
        "organization": {
            "id": str(user.organization.id),
            "name": user.organization.name,
            "external_id": user.organization.external_id,
        },
    }


